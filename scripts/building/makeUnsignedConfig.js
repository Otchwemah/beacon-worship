// Beacon Worship: generate an UNSIGNED electron-builder config for local/manual installer builds.
//
// Why this exists: config/building/electron-builder.yaml is set up for the upstream signed
// release pipeline. It has:
//   - afterSign: scripts/macos/notarize.js  -> calls Apple notarization unconditionally on macOS
//   - win.azureSignOptions                  -> Azure Trusted Signing
// Both require credentials that a normal build does not have, so an ordinary
// `electron-builder` run fails. This script derives a config with signing disabled, keeping
// every other setting (branding, icon paths, file filters, DMG layout) in sync with the real one
// instead of duplicating the file and letting it drift.
//
// It does NOT publish anything. Pair it with `--publish never`.
//
// Usage: node scripts/building/makeUnsignedConfig.js [outputPath]

const fs = require("fs")
const path = require("path")

// js-yaml is a production dependency of electron-builder (app-builder-lib / builder-util /
// dmg-builder), so `npm ci` always provides it hoisted at node_modules/js-yaml. It is not a
// direct dependency of this project, hence the explicit guidance if it is ever absent.
let yaml
try {
    yaml = require("js-yaml")
} catch {
    console.error("Could not load js-yaml. Run `npm ci` first (it ships with electron-builder).")
    process.exit(1)
}

const projectRoot = path.join(__dirname, "..", "..")
const sourcePath = path.join(projectRoot, "config", "building", "electron-builder.yaml")
const defaultOutput = path.join(projectRoot, "config", "building", "electron-builder.unsigned.generated.yaml")

function makeUnsigned(config) {
    const out = JSON.parse(JSON.stringify(config))

    // macOS: ad-hoc sign instead of skipping signing outright.
    //
    // electron-builder's macOptions docs are explicit:
    //   identity null -> "skip signing entirely"
    //   identity "-"  -> "opt in to ad-hoc signing explicitly"
    // Skipping signing leaves the modified Electron frameworks with invalidated signatures,
    // which Apple Silicon macOS reports as '"Beacon Worship" is damaged and can't be opened'.
    // Ad-hoc signing produces a valid (though not Apple-notarized) signature, so the app opens
    // after the usual right-click -> Open, without the "damaged" error.
    //
    // hardenedRuntime MUST be false with ad-hoc signing, otherwise library validation rejects
    // the pre-signed Electron frameworks that carry a different Team ID.
    delete out.afterSign
    if (out.mac) {
        out.mac.identity = "-"
        out.mac.notarize = false
        out.mac.hardenedRuntime = false
        out.mac.gatekeeperAssess = false
        // entitlements are only meaningful for a real signed + notarized build
        delete out.mac.entitlements
        delete out.mac.entitlementsInherit
    }

    // Windows: drop Azure Trusted Signing so the installer is simply unsigned.
    if (out.win) delete out.win.azureSignOptions

    // never let a stray CSC env var trigger signing
    out.forceCodeSigning = false

    // Shrink the download. GitHub artifact downloads cannot be resumed in a browser, so a
    // smaller installer materially reduces the chance of a stalled transfer.
    out.compression = "maximum"

    return out
}

function main() {
    const outputPath = process.argv[2] ? path.resolve(process.argv[2]) : defaultOutput

    const raw = fs.readFileSync(sourcePath, "utf8")
    const config = yaml.load(raw)
    const unsigned = makeUnsigned(config)

    const header = ["# GENERATED by scripts/building/makeUnsignedConfig.js - do not edit or commit.", "# Unsigned build config derived from electron-builder.yaml. Build with --publish never.", ""].join("\n")

    fs.writeFileSync(outputPath, header + yaml.dump(unsigned, { lineWidth: 200, noRefs: true }))

    console.log(`Wrote unsigned config: ${path.relative(projectRoot, outputPath)}`)
    console.log(`productName: ${unsigned.productName}`)
    console.log(`mac.identity: ${unsigned.mac ? unsigned.mac.identity : "(no mac section)"}`)
    console.log(`afterSign present: ${"afterSign" in unsigned}`)
    console.log(`win.azureSignOptions present: ${!!(unsigned.win && unsigned.win.azureSignOptions)}`)
}

if (require.main === module) main()

module.exports = { makeUnsigned }
